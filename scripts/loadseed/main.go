package main

import (
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strings"
)

const (
	defaultRiders = 500
	defaultOrders = 10000
)

type options struct {
	riders int
	orders int
	seed   int64
	output string
}

func main() {
	config := options{}
	flag.IntVar(&config.riders, "riders", defaultRiders, "number of load-test riders")
	flag.IntVar(&config.orders, "orders", defaultOrders, "number of load-test orders")
	flag.Int64Var(&config.seed, "seed", 20261019, "deterministic dataset seed")
	flag.StringVar(&config.output, "output", "db/seed/load.sql", "output SQL file")
	flag.Parse()

	if config.riders < 1 || config.orders < 1 {
		fmt.Fprintln(os.Stderr, "riders and orders must both be positive")
		os.Exit(2)
	}

	contents := generateSQL(config)
	if err := os.MkdirAll(filepath.Dir(config.output), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "create output directory: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(config.output, []byte(contents), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write load seed: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d riders and %d orders to %s\n", config.riders, config.orders, config.output)
}

func generateSQL(config options) string {
	var sql strings.Builder
	fmt.Fprintf(&sql, "-- Generated by scripts/loadseed. seed=%d riders=%d orders=%d\n", config.seed, config.riders, config.orders)
	sql.WriteString("-- Load the normal seed/reference data first. This file only owns load_* rows.\n")
	sql.WriteString("BEGIN;\n")
	sql.WriteString("DELETE FROM orders WHERE id LIKE 'load_ord_%';\n")
	sql.WriteString("DELETE FROM riders WHERE id LIKE 'load_rider_%';\n\n")

	sql.WriteString("INSERT INTO riders (id, full_name, phone, is_available, max_capacity, current_orders_count, last_lat, last_lng, last_bearing_deg, last_speed_kmh, location_updated_at, offers_count, accepted_count) VALUES\n")
	for index := 0; index < config.riders; index++ {
		latitude, longitude := riderLocation(index, config.seed)
		bearing := float64((index * 37) % 360)
		separator := ",\n"
		if index == config.riders-1 {
			separator = ";\n\n"
		}
		fmt.Fprintf(&sql, "  ('load_rider_%06d', 'Load Rider %06d', '+25473%07d', TRUE, 5, 0, %.6f, %.6f, %.3f, 20, now(), 0, 0)%s", index+1, index+1, index+1, latitude, longitude, bearing, separator)
	}

	sql.WriteString("INSERT INTO orders (id, vendor_id, category_code, status, pickup_lat, pickup_lng, delivery_lat, delivery_lng, trip_distance_m, trip_bearing_deg, value_cents, delivery_fee_cents, rider_payout_bps, created_at) VALUES\n")
	for index := 0; index < config.orders; index++ {
		vendor, category, pickupLat, pickupLng, deliveryLat, deliveryLng := orderLocations(index, config.seed)
		distance := haversineMetres(pickupLat, pickupLng, deliveryLat, deliveryLng)
		bearing := bearingDegrees(pickupLat, pickupLng, deliveryLat, deliveryLng)
		separator := ",\n"
		if index == config.orders-1 {
			separator = ";\n"
		}
		ageSeconds := (config.orders - index) * 6
		valueCents := 10000 + (index%1000)*250
		feeCents := 1000 + (index%50)*100
		fmt.Fprintf(&sql, "  ('load_ord_%08d', '%s', '%s', 'pending', %.6f, %.6f, %.6f, %.6f, %d, %.3f, %d, %d, 9000, now() - interval '%d seconds')%s", index+1, vendor, category, pickupLat, pickupLng, deliveryLat, deliveryLng, distance, bearing, valueCents, feeCents, ageSeconds, separator)
	}
	sql.WriteString("COMMIT;\n")
	return sql.String()
}

func riderLocation(index int, seed int64) (float64, float64) {
	cluster := int((int64(index)*31 + seed) % 4)
	if cluster < 0 {
		cluster += 4
	}
	base := [4][2]float64{{-1.265, 36.804}, {-1.285, 36.817}, {-1.292, 36.787}, {-1.310, 36.833}}
	offset := float64((index*17)%1000) / 100000.0
	return base[cluster][0] + offset, base[cluster][1] + offset/2
}

func orderLocations(index int, seed int64) (string, string, float64, float64, float64, float64) {
	cluster := int((int64(index)*13 + seed) % 4)
	if cluster < 0 {
		cluster += 4
	}
	base := [4][2]float64{{-1.265, 36.804}, {-1.285, 36.817}, {-1.292, 36.787}, {-1.310, 36.833}}
	vendors := [4]string{"ven_001", "ven_003", "ven_004", "ven_006"}
	categories := [6]string{"electronics", "food", "documents", "clothing", "fragile", "groceries"}
	pickupOffset := float64((index*19)%2000) / 1000000.0
	deliveryOffset := float64((index*23)%5000) / 100000.0
	pickupLat := base[cluster][0] + pickupOffset
	pickupLng := base[cluster][1] + pickupOffset/2
	deliveryLat := pickupLat + 0.005 + deliveryOffset/10
	deliveryLng := pickupLng + 0.008 + deliveryOffset/10
	return vendors[cluster], categories[index%len(categories)], pickupLat, pickupLng, deliveryLat, deliveryLng
}

func haversineMetres(firstLat, firstLng, secondLat, secondLng float64) int {
	const earthRadiusMetres = 6371000.0
	latitudeOne := firstLat * math.Pi / 180
	latitudeTwo := secondLat * math.Pi / 180
	deltaLatitude := (secondLat - firstLat) * math.Pi / 180
	deltaLongitude := (secondLng - firstLng) * math.Pi / 180
	a := math.Sin(deltaLatitude/2)*math.Sin(deltaLatitude/2) + math.Cos(latitudeOne)*math.Cos(latitudeTwo)*math.Sin(deltaLongitude/2)*math.Sin(deltaLongitude/2)
	return int(math.Round(earthRadiusMetres * 2 * math.Atan2(math.Sqrt(a), math.Sqrt(1-a))))
}

func bearingDegrees(firstLat, firstLng, secondLat, secondLng float64) float64 {
	latitudeOne := firstLat * math.Pi / 180
	latitudeTwo := secondLat * math.Pi / 180
	deltaLongitude := (secondLng - firstLng) * math.Pi / 180
	y := math.Sin(deltaLongitude) * math.Cos(latitudeTwo)
	x := math.Cos(latitudeOne)*math.Sin(latitudeTwo) - math.Sin(latitudeOne)*math.Cos(latitudeTwo)*math.Cos(deltaLongitude)
	return math.Mod(math.Atan2(y, x)*180/math.Pi+360, 360)
}
